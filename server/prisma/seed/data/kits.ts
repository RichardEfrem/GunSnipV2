import type { DecalType, Difficulty } from '@gunsnip/shared';
import type { VariantSeed } from './tools.ts';

/**
 * Model kit catalogue.
 *
 * Every field here is a first-class column rather than JSONB, because every one of them drives
 * the filter rail (PRD §5.1) and a filter over JSONB is neither fast nor consistent. Kits are
 * near-always single-variant — a boxed kit is a boxed kit — so most have exactly one.
 */
export interface KitSeed {
  slug: string;
  name: string;
  categorySlug: string;
  gradeCode: string;
  scaleCode: string;
  seriesSlug: string;
  /** The mobile suit, distinct from the product name. */
  unitName: string;
  /** Heavily searched, indexed for both FTS and trigram. */
  unitCode: string;
  runnerCount: number;
  partCount: number;
  difficulty: Difficulty;
  decalType: DecalType;
  articulationNotes: string;
  includes: readonly string[];
  releaseYear: number;
  runtimeMinutesEst: number;
  description: string;
  tags: readonly string[];
  variants: readonly VariantSeed[];
}

const single = (
  sku: string,
  priceIdr: number,
  stockOnHand: number,
  weightGrams: number,
  compareAtPriceIdr?: number,
): readonly VariantSeed[] => [{ sku, priceIdr, stockOnHand, weightGrams, ...(compareAtPriceIdr === undefined ? {} : { compareAtPriceIdr }) }];

